-- Tạo 13 bảng nghiệp vụ; Flyway quản lý phiên bản, Hibernate chỉ kiểm tra ánh xạ.
CREATE TABLE VAI_TRO (
    MaVaiTro VARCHAR(10) NOT NULL,
    TenVaiTro VARCHAR(50) NOT NULL,
    PRIMARY KEY (MaVaiTro),
    CONSTRAINT UK_VAI_TRO_TenVaiTro UNIQUE (TenVaiTro)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE NHAN_VIEN (
    MaNV VARCHAR(10) NOT NULL,
    HoTen VARCHAR(100) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    SDT VARCHAR(15) NULL,
    MatKhau VARCHAR(255) NOT NULL,
    MaVaiTro VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaNV),
    CONSTRAINT UK_NHAN_VIEN_Email UNIQUE (Email),
    CONSTRAINT FK_NHAN_VIEN_VAI_TRO FOREIGN KEY (MaVaiTro)
        REFERENCES VAI_TRO (MaVaiTro) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE KHACH_HANG (
    MaKH VARCHAR(10) NOT NULL,
    HoTen VARCHAR(100) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    SDT VARCHAR(15) NULL,
    MatKhau VARCHAR(255) NOT NULL,
    DiaChi VARCHAR(200) NULL,
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MaKH),
    CONSTRAINT UK_KHACH_HANG_Email UNIQUE (Email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE LOAI_PHONG (
    MaLoaiPhong VARCHAR(10) NOT NULL,
    TenLoaiPhong VARCHAR(50) NOT NULL,
    GiaMoiDem DECIMAL(12,2) NOT NULL,
    SucChua INT NOT NULL,
    MoTa VARCHAR(255) NULL,
    PRIMARY KEY (MaLoaiPhong),
    CONSTRAINT UK_LOAI_PHONG_TenLoaiPhong UNIQUE (TenLoaiPhong),
    CONSTRAINT CK_LOAI_PHONG_GiaMoiDem CHECK (GiaMoiDem > 0),
    CONSTRAINT CK_LOAI_PHONG_SucChua CHECK (SucChua > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE PHONG (
    MaPhong VARCHAR(10) NOT NULL,
    SoPhong VARCHAR(10) NOT NULL,
    Tang INT NULL,
    TrangThai VARCHAR(20) NOT NULL DEFAULT 'TRONG',
    MaLoaiPhong VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaPhong),
    CONSTRAINT UK_PHONG_SoPhong UNIQUE (SoPhong),
    CONSTRAINT CK_PHONG_TrangThai CHECK (TrangThai IN ('TRONG','CO_KHACH','DANG_DON','BAO_TRI')),
    CONSTRAINT FK_PHONG_LOAI_PHONG FOREIGN KEY (MaLoaiPhong)
        REFERENCES LOAI_PHONG (MaLoaiPhong) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DAT_PHONG (
    MaDatPhong VARCHAR(10) NOT NULL,
    NgayDat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NgayNhanPhong DATE NOT NULL,
    NgayTraPhong DATE NOT NULL,
    TrangThai VARCHAR(20) NOT NULL DEFAULT 'CHO_THANH_TOAN',
    TongTien DECIMAL(12,2) NOT NULL DEFAULT 0,
    MaKH VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NULL,
    PRIMARY KEY (MaDatPhong),
    CONSTRAINT CK_DAT_PHONG_Ngay CHECK (NgayTraPhong > NgayNhanPhong),
    CONSTRAINT CK_DAT_PHONG_TrangThai CHECK (TrangThai IN ('CHO_THANH_TOAN','DA_XAC_NHAN','DA_HUY','HOAN_TAT')),
    CONSTRAINT FK_DAT_PHONG_KHACH_HANG FOREIGN KEY (MaKH)
        REFERENCES KHACH_HANG (MaKH) ON DELETE RESTRICT,
    CONSTRAINT FK_DAT_PHONG_NHAN_VIEN FOREIGN KEY (MaNV)
        REFERENCES NHAN_VIEN (MaNV) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CHI_TIET_DAT_PHONG (
    MaCTDP VARCHAR(10) NOT NULL,
    SoLuongKhach INT NOT NULL,
    GiaThoiDiemDat DECIMAL(12,2) NOT NULL,
    MaDatPhong VARCHAR(10) NOT NULL,
    MaPhong VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaCTDP),
    CONSTRAINT UK_CHI_TIET_DAT_PHONG_DonPhong UNIQUE (MaDatPhong, MaPhong),
    CONSTRAINT CK_CHI_TIET_DAT_PHONG_SoLuongKhach CHECK (SoLuongKhach > 0),
    CONSTRAINT FK_CHI_TIET_DAT_PHONG_DAT_PHONG FOREIGN KEY (MaDatPhong)
        REFERENCES DAT_PHONG (MaDatPhong) ON DELETE RESTRICT,
    CONSTRAINT FK_CHI_TIET_DAT_PHONG_PHONG FOREIGN KEY (MaPhong)
        REFERENCES PHONG (MaPhong) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DICH_VU (
    MaDichVu VARCHAR(10) NOT NULL,
    TenDichVu VARCHAR(100) NOT NULL,
    DonGia DECIMAL(12,2) NOT NULL,
    CachTinh VARCHAR(20) NOT NULL,
    DonViTinh VARCHAR(30) NOT NULL,
    MoTa VARCHAR(255) NULL,
    PRIMARY KEY (MaDichVu),
    CONSTRAINT UK_DICH_VU_TenDichVu UNIQUE (TenDichVu),
    CONSTRAINT CK_DICH_VU_DonGia CHECK (DonGia > 0),
    CONSTRAINT CK_DICH_VU_CachTinh CHECK (CachTinh IN ('THEO_DEM','MOT_LAN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CHI_TIET_DICH_VU (
    MaCTDV VARCHAR(10) NOT NULL,
    SoLuong INT NOT NULL,
    DonGiaThoiDiemDat DECIMAL(12,2) NOT NULL,
    MaDatPhong VARCHAR(10) NOT NULL,
    MaDichVu VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaCTDV),
    CONSTRAINT UK_CHI_TIET_DICH_VU_DonDichVu UNIQUE (MaDatPhong, MaDichVu),
    CONSTRAINT CK_CHI_TIET_DICH_VU_SoLuong CHECK (SoLuong BETWEEN 1 AND 10),
    CONSTRAINT FK_CHI_TIET_DICH_VU_DAT_PHONG FOREIGN KEY (MaDatPhong)
        REFERENCES DAT_PHONG (MaDatPhong) ON DELETE RESTRICT,
    CONSTRAINT FK_CHI_TIET_DICH_VU_DICH_VU FOREIGN KEY (MaDichVu)
        REFERENCES DICH_VU (MaDichVu) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE HOA_DON (
    MaHoaDon VARCHAR(10) NOT NULL,
    NgayLap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TongTien DECIMAL(12,2) NOT NULL,
    TrangThaiThanhToan VARCHAR(20) NOT NULL DEFAULT 'CHUA_THANH_TOAN',
    MaDatPhong VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaHoaDon),
    CONSTRAINT UK_HOA_DON_MaDatPhong UNIQUE (MaDatPhong),
    CONSTRAINT CK_HOA_DON_TrangThaiThanhToan CHECK (TrangThaiThanhToan IN ('CHUA_THANH_TOAN','DA_COC','DA_HOAN_TAT')),
    CONSTRAINT FK_HOA_DON_DAT_PHONG FOREIGN KEY (MaDatPhong)
        REFERENCES DAT_PHONG (MaDatPhong) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE THANH_TOAN (
    MaThanhToan VARCHAR(10) NOT NULL,
    PhuongThuc VARCHAR(20) NOT NULL,
    SoTien DECIMAL(12,2) NOT NULL,
    NgayThanhToan DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai VARCHAR(20) NOT NULL DEFAULT 'DANG_XU_LY',
    GhiChu VARCHAR(200) NULL,
    MaHoaDon VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaThanhToan),
    CONSTRAINT CK_THANH_TOAN_PhuongThuc CHECK (PhuongThuc IN ('TRUC_TUYEN','TIEN_MAT','THE')),
    CONSTRAINT CK_THANH_TOAN_SoTien CHECK (SoTien > 0),
    CONSTRAINT CK_THANH_TOAN_TrangThai CHECK (TrangThai IN ('DANG_XU_LY','THANH_CONG','THAT_BAI')),
    CONSTRAINT FK_THANH_TOAN_HOA_DON FOREIGN KEY (MaHoaDon)
        REFERENCES HOA_DON (MaHoaDon) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DANH_GIA (
    MaDanhGia VARCHAR(10) NOT NULL,
    SoSao INT NOT NULL,
    NoiDung VARCHAR(500) NULL,
    NgayDanhGia DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MaDatPhong VARCHAR(10) NOT NULL,
    PRIMARY KEY (MaDanhGia),
    CONSTRAINT UK_DANH_GIA_MaDatPhong UNIQUE (MaDatPhong),
    CONSTRAINT CK_DANH_GIA_SoSao CHECK (SoSao BETWEEN 1 AND 5),
    CONSTRAINT FK_DANH_GIA_DAT_PHONG FOREIGN KEY (MaDatPhong)
        REFERENCES DAT_PHONG (MaDatPhong) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE THAM_SO (
    MaThamSo VARCHAR(30) NOT NULL,
